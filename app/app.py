"""Hotel intelligence assistant: search guest photos and reviews in plain English (Step 10). Runs on this computer.

    .venv/bin/streamlit run app/app.py --server.port 8507
    VIEW_ONLY=1 .venv/bin/streamlit run app/app.py --server.port 8507    # for demos: no API calls (D22)

Ask a question → the app reads it (topic, sentiment, what to look for) → shows the matching photos with their
reviews and match scores → on request, Claude Sonnet 5.5 writes a short answer from that evidence only (D16).
Search is free and local; each answer costs about 1 cent and sends the shown photos and reviews to Anthropic.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

os.environ.setdefault("ANONYMIZED_TELEMETRY", "False")
import torch  # noqa: E402

# Streamlit runs each search in a fresh thread; with several PyTorch threads, starting them again each time could
# add up to 2 s. One short question needs only one thread: first search 2.07 s -> 0.27 s, later ones about 0.08 s.
torch.set_num_threads(1)
import anthropic  # noqa: E402
import streamlit as st  # noqa: E402
from dotenv import load_dotenv  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from answer import MODEL as ANSWER_MODEL, answer  # noqa: E402
from search import TOPIC_WORDS, Searcher  # noqa: E402

IMAGES = ROOT / "data" / "selected" / "images"
EXAMPLES = ["Show room images associated with negative feedback.", "Find hotel facilities associated with positive feedback.",
            "Show public areas mentioned in negative reviews.", "Find images connected with positive comments about food.",
            "What are customers saying about the rooms shown in these images?", "Show me the swimming pools"]
APPROACHES = {"Photo search, SigLIP (recommended)": ("image", "siglip"), "Photo search, CLIP": ("image", "clip"),
              "Caption search, SigLIP": ("caption", "siglip"), "Keyword search on descriptions": ("keyword", "siglip")}
TOPIC_NAMES = {"Public_area": "Public area"}
# View-only mode for demos (D22): search works as usual, but the paid answer button is hidden, so no API calls.
VIEW_ONLY = os.environ.get("VIEW_ONLY", "").strip().lower() in {"1", "true", "yes"}
SENTIMENT_COLOURS = {"Positive": "#2e7d32", "Neutral": "#6b7280", "Negative": "#c62828"}

st.set_page_config(page_title="Hotel intelligence assistant", page_icon="🏨", layout="wide")


@st.cache_resource(show_spinner="Loading the search models (first time only)…")
def searcher() -> Searcher:
    s = Searcher()
    for name, model in s.models.items():   # warm up once here, so the first real search is quick too
        vec = model.texts(["a hotel room"]).tolist()
        s.db.get_collection(f"images_{name}").query(query_embeddings=vec, n_results=1, where={"Room_Negative": True})
    return s


def badge(text: str, colour: str) -> str:
    return f"<span style='background:{colour};color:white;padding:2px 8px;border-radius:9px;font-size:0.8em;margin-right:4px'>{text}</span>"


def label_badges(labels: str) -> str:
    out = []
    for l in (labels or "").split("; "):
        if "#" in l:
            topic, polarity = l.split("#")
            out.append(badge(f"{TOPIC_NAMES.get(topic, topic)} {polarity.lower()}", SENTIMENT_COLOURS.get(polarity, "#6b7280")))
    return "".join(out)


def show_results(hits: list[dict], how: dict, asked_topics: list[str]):
    top = max((h["score"] for h in hits), default=1) or 1
    cols = st.columns(3)
    for n, h in enumerate(hits, 1):
        with cols[(n - 1) % 3]:
            st.image(str(IMAGES / h["image_file"]), use_container_width=True)
            st.markdown(f"**E{n}** · {h['scene_type']} · match {h['score'] / top:.0%} of the best "
                        f"<span style='color:#6b7280;font-size:0.8em'>(score {h['score']:.3f})</span>", unsafe_allow_html=True)
            st.markdown(label_badges(h["labels"]), unsafe_allow_html=True)
            shows = [t for t in asked_topics if t in h["image_topics"].split("; ")]
            if asked_topics and not shows:
                st.caption("⚠️ The dataset's own label says this photo shows "
                           f"{h['image_topics'].replace('_', ' ').lower()}, not what the question asks about.")
            st.write(f"“{h['review_en']}”")
            with st.expander("More: original review, description, similar photos"):
                st.caption("Original review (Vietnamese, from the source):")
                st.write(h["review_vi"])
                st.caption("Photo description (generated by Claude Opus 5.5):")
                st.write(h["description"])
                if st.button("Show photos like this one", key=f"similar-{h['image_file']}"):
                    st.session_state.similar = h["image_file"]
                    st.rerun()


st.title("🏨 Hotel intelligence assistant")
st.caption("Search 501 guest photos and 267 reviews from the ViMACSA dataset (research use only). Reviews are shown in "
           "English, translated by Claude and kept beside the Vietnamese original. A prototype.")

with st.sidebar:
    st.header("Settings")
    approach_name = st.selectbox("Search method", list(APPROACHES))
    k = st.slider("Photos to show", 3, 12, 6, 3)
    use_labels = st.checkbox("Use the reviews' topic and sentiment labels", value=True,
                             help="Photos can't show how a guest felt, so 'negative' and 'positive' come from the review's own label.")
    st.divider()
    if VIEW_ONLY:
        st.info("**View-only mode.** Search runs on this computer and is free. Written answers are switched off, "
                "so there are no calls to Claude and no API cost.")
    st.caption("About the match score: it compares the question with each photo. Scores differ between methods, "
               "so the app shows each one as a share of the best match in this search.")

question = st.text_input("Ask a question", placeholder="e.g. Show room images associated with negative feedback")
st.caption("Examples:")
ex_cols = st.columns(3)
for i, ex in enumerate(EXAMPLES):
    if ex_cols[i % 3].button(ex, key=f"ex{i}", use_container_width=True):
        st.session_state.question = ex
        st.session_state.pop("similar", None)
        st.rerun()
question = question or st.session_state.get("question", "")

s = searcher()
if st.session_state.get("similar"):
    hits, how = s.similar(st.session_state.similar, k=k)
    st.subheader("Photos that look like the one you picked")
    st.image(str(IMAGES / st.session_state.similar), width=220)
    if st.button("← Back to the question"):
        st.session_state.pop("similar")
        st.rerun()
    show_results(hits, how, [])
elif question:
    approach, model = APPROACHES[approach_name]
    hits, how = s.search(question, approach, model, k=k, use_labels=use_labels)
    topics = ", ".join(TOPIC_NAMES.get(t, t) for t in how["topics"]) or "any topic"
    st.markdown(f"**Understood as:** topic {topics} · sentiment {how['sentiment'] or 'any'} · looking for "
                f"*{how['look_for'].replace('a photo of ', '')}* · {len(hits)} photos in {how['seconds']:.2f} s")
    if not hits:
        st.info("Nothing matches. Try other words, or turn off the labels in the settings.")
    else:
        answer_box = st.container()
        show_results(hits, how, how["topics"] if use_labels else [])
        with answer_box:
            key = (question, approach_name, k, use_labels)
            if st.session_state.get("answer_for") != key:
                st.session_state.pop("answer", None)
            if not VIEW_ONLY and st.button(f"✍️ Write a short answer from these photos and reviews (about 1 cent, {ANSWER_MODEL})"):
                load_dotenv(ROOT / ".env")
                with st.spinner("Claude is reading the evidence…"):
                    st.session_state.answer = answer(anthropic.Anthropic(), question, hits)
                    st.session_state.answer_for = key
            r = st.session_state.get("answer")
            if r:
                if r["answer"]:
                    a = r["answer"]
                    box = st.success if a["enough_evidence"] else st.warning
                    box(("" if a["enough_evidence"] else "The evidence doesn't fully answer this question. ") + a["answer"])
                    for p in a["points"]:
                        st.markdown(f"- {p['point']} *({', '.join(p['evidence'])})*")
                    st.caption(f"Written by {r['model_used']} from the {len(hits)} items shown, in {r['seconds']} s, "
                               f"${r['cost_usd']:.3f}. E1, E2 … are the photos below.")
                else:
                    st.error(f"No answer: {r['status']}")
else:
    st.info("Type a question, or pick an example.")
